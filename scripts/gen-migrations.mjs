// Embeds db/migrations-*.sql into src/lib/migrations.generated.ts so the server can apply
// them itself on start-up (src/lib/migrate.ts). Runs before every build (npm "prebuild").
// Every migration file must be safe to run more than once (IF NOT EXISTS etc.).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "db");
const files = readdirSync(dir).filter((f) => /^migrations-.+\.sql$/.test(f)).sort();
const items = files.map((f) => ({ id: f.replace(/\.sql$/, ""), sql: readFileSync(join(dir, f), "utf8") }));
const out = `// Generated by scripts/gen-migrations.mjs from db/migrations-*.sql. Do not edit.
export const MIGRATIONS: { id: string; sql: string }[] = ${JSON.stringify(items, null, 2)};
`;
writeFileSync(join(root, "src/lib/migrations.generated.ts"), out);
console.log(`migrations: embedded ${items.length} files`);
